CREATE TABLE IF NOT EXISTS users (
 userId INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 userName VARCHAR(60) NOT NULL UNIQUE, email VARCHAR(190) NOT NULL UNIQUE,
 password VARCHAR(255) NOT NULL, role ENUM('user','admin') NOT NULL DEFAULT 'user'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
CREATE TABLE IF NOT EXISTS ratings (
 userId INT UNSIGNED NOT NULL, menuId INT UNSIGNED NOT NULL, score TINYINT UNSIGNED NOT NULL,
 PRIMARY KEY(userId,menuId), CHECK(score BETWEEN 1 AND 5),
 FOREIGN KEY(userId) REFERENCES users(userId) ON DELETE CASCADE,
 FOREIGN KEY(menuId) REFERENCES menus(menuId) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
